export interface TimingWindow {
  urgency: TimingUrgency;
  reason: string;
  expires_at: string | null;
}

/** Fully-typed strategy contract — required for READY_TO_ACTION battlecards. */
export interface StrategySchema {
  pain_point: string;
  closing_argument: string;
  timing_window: TimingWindow;
  playbook: string;
  next_best_action: string;
  channel: string;
  rationale: string | null;
  generator: string;
  generator_version: string;
  generated_at: string;
  confidence_score: number;
  manual_review_required: boolean;
  variant_id: string | null;
  variant_arm: string | null;
}

/** Partial strategy while opportunity is still being enriched. */
export type StrategyPartial = Partial<StrategySchema> & Record<string, unknown>;

// ── OpportunityOut ────────────────────────────────────────────────────────────

/**
 * Revenue Continuity Radar classification — see
 * app.models.base.OPPORTUNITY_TYPES / RevenueContinuityService on the
 * backend. "expansion"/"renewal_risk" only ever appear on a signal about a
 * company that already has a WON opportunity; every net-new prospect is
 * "new_logo".
 */
export type OpportunityType = "new_logo" | "expansion" | "renewal_risk";

export interface Opportunity {
  id: string;
  title: string;
  status: OpportunityStatus;
  opportunity_type: OpportunityType;
  score: number;
  strategy: StrategyPartial;
  signal_id: string | null;
  lead_id: string | null;
  company_id: string | null;
  assigned_to_user_id: string | null;
  // Forecasting & MEDDIC qualification — filled in by the rep, never
  // generated by BEE. See MeddicCriterion in lib/forecast.ts.
  amount: number | null;
  expected_close_date: string | null;
  qualification: Record<string, boolean>;
  // Deal context captured at manual creation — see new-opportunity-form.tsx.
  source: string | null;
  next_meeting_at: string | null;
  meetings_held_count: number;
  photo_url: string | null;
  created_at: string;
  updated_at: string;
  // Win/Loss Analysis — null until PATCH /{id}/outcome is called.
  loss_reason: LossReason | null;
  competitor: string | null;
  closed_at: string | null;
}

