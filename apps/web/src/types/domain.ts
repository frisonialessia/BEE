/** Where a new lead can land in the pipeline at creation time — mirrors
 * LEAD_PIPELINE_STAGES on the backend (schemas/lead.py). Deliberately
 * excludes ready_to_action (an earned state, never picked by hand — see
 * that constant's own comment) and the closed statuses. */
export type LeadPipelineStage = "detected" | "prioritized" | "in_progress";

/** "Ligado al cerebro de BEE" — what kind of account a meeting is with,
 * derived server-side from the linked Opportunity/Lead (see
 * app.api.v1.endpoints.meetings._client_context). Never set by hand. */
export type MeetingClientContext = "active_client" | "hot_lead" | "prospect" | "new_contact";

/** Personal color tag — picked freely by whoever creates the meeting,
 * purely organizational (unlike MeetingClientContext). Token names, not
 * raw hex — resolve through the same --color-chart-1..6 custom properties
 * everything else already uses. Mirrors MeetingColor in schemas/meeting.py. */
export type MeetingColor = "chart-1" | "chart-2" | "chart-3" | "chart-4" | "chart-5" | "chart-6" | "green-1" | "green-2" | "green-3";

export interface Meeting {
  id: string;
  created_by_user_id: string;
  opportunity_id: string | null;
  lead_id: string | null;
  title: string;
  purpose: string | null;
  starts_at: string;
  duration_minutes: number;
  meeting_url: string | null;
  attendee_user_ids: string[];
  // {user_id: "accepted" | "declined"} — an attendee id with no entry here
  // is implicitly "pending" (hasn't responded yet). See POST
  // /meetings/{id}/respond on the backend.
  attendee_responses: Record<string, "accepted" | "declined">;
  color: MeetingColor | null;
  // Set once via POST /meetings/{id}/complete — a scheduled meeting alone
  // never sets this. See that endpoint's own docstring for why the
  // distinction matters (this is what feeds the meeting back into
  // meetings_held_count and an engagement signal, nothing else does).
  completed_at: string | null;
  created_at: string;
  company_name: string | null;
  contact_name: string | null;
  client_context: MeetingClientContext | null;
}
